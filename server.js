// Loads Express so the application can create routes and respond to requests.
const express = require("express");

// Loads Node's file system tools so the program can save and read catch data.
const fs = require("fs");

// Helps create reliable file paths on different computers.
const path = require("path");


// Creates the Express application.
const app = express();

// The port is the address where the local server will run.
const port = 3000;

// Creates the path to the persistent catch data file.
const dataFilePath = path.join(__dirname, "catches.json");


// Allows Express to understand JSON sent from the browser.
app.use(express.json());


// Loads saved catches from catches.json.
function loadCatches() {
    try {
        const fileContents = fs.readFileSync(dataFilePath, "utf8");
        const savedCatches = JSON.parse(fileContents);

        if (!Array.isArray(savedCatches)) {
            return [];
        }

        return savedCatches.map(function (fish, index) {
            return {
                id: fish.id || String(index + 1),
                species: fish.species,
                location: fish.location,
                length: Number(fish.length),
                lure: fish.lure,
                date: fish.date
            };
        });
    } catch (error) {
        console.log(
            "No saved catches were found. Starting with an empty list."
        );

        return [];
    }
}


// Saves the current catches to catches.json.
function saveCatches() {
    fs.writeFileSync(
        dataFilePath,
        JSON.stringify(catches, null, 2)
    );
}


// Loads catches when the server starts.
let catches = loadCatches();


// Prevents user-entered text from being treated as HTML.
function escapeHtml(value) {
    return String(value)
        .replaceAll("&", "&amp;")
        .replaceAll("<", "&lt;")
        .replaceAll(">", "&gt;")
        .replaceAll('"', "&quot;")
        .replaceAll("'", "&#039;");
}


// Checks whether catch information is valid.
function isValidCatch(fish) {
    return (
        fish &&
        String(fish.species).trim() !== "" &&
        String(fish.location).trim() !== "" &&
        String(fish.lure).trim() !== "" &&
        String(fish.date).trim() !== "" &&
        Number.isFinite(Number(fish.length)) &&
        Number(fish.length) > 0
    );
}


// Creates rows for the dynamically generated catch table.
function createCatchRows(catchList) {
    if (catchList.length === 0) {
        return `
            <tr>
                <td colspan="6">No catches found.</td>
            </tr>
        `;
    }

    return catchList.map(function (fish) {
        return `
            <tr>
                <td>${escapeHtml(fish.species)}</td>
                <td>${escapeHtml(fish.location)}</td>
                <td>${fish.length} inches</td>
                <td>${escapeHtml(fish.lure)}</td>
                <td>${escapeHtml(fish.date)}</td>
                <td>${escapeHtml(fish.id)}</td>
            </tr>
        `;
    }).join("");
}


// Creates the statistics page dynamically.
function createStatsPage() {
    const totalFish = catches.length;

    const totalInches = catches.reduce(function (total, fish) {
        return total + fish.length;
    }, 0);

    const averageLength =
        totalFish > 0 ? (totalInches / totalFish).toFixed(2) : "0";

    let largestFish = null;

    if (totalFish > 0) {
        largestFish = catches.reduce(function (largest, fish) {
            return fish.length > largest.length ? fish : largest;
        });
    }

    const largestFishText = largestFish
        ? `${escapeHtml(largestFish.species)} - ${largestFish.length} inches`
        : "None";

    return `
        <!DOCTYPE html>
        <html lang="en">
        <head>
            <meta charset="UTF-8">
            <meta name="viewport" content="width=device-width, initial-scale=1.0">
            <title>Fishing Statistics</title>
            <link rel="stylesheet" href="/style.css">
        </head>

        <body>
            <header>
                <h1>Fishing Statistics</h1>
                <p>Statistics generated by Express and saved data.</p>
            </header>

            <main>
                <section>
                    <h2>Server Statistics</h2>

                    <p>Total Fish: ${totalFish}</p>
                    <p>Total Inches: ${totalInches}</p>
                    <p>Average Length: ${averageLength} inches</p>
                    <p>Largest Fish: ${largestFishText}</p>

                    <p>
                        <a href="/">Return to Fishing Tracker</a>
                    </p>

                    <p>
                        <a href="/catches">View Detailed Catch Log</a>
                    </p>
                </section>
            </main>
        </body>
        </html>
    `;
}


// Creates the detailed catch log page dynamically.
function createCatchesPage() {
    return `
        <!DOCTYPE html>
        <html lang="en">
        <head>
            <meta charset="UTF-8">
            <meta name="viewport" content="width=device-width, initial-scale=1.0">
            <title>Detailed Catch Log</title>
            <link rel="stylesheet" href="/style.css">
        </head>

        <body>
            <header>
                <h1>Detailed Catch Log</h1>
                <p>All catches currently saved by the server.</p>
            </header>

            <main>
                <section>
                    <h2>Server-Saved Catches</h2>

                    <table>
                        <tr>
                            <th>Species</th>
                            <th>Location</th>
                            <th>Length</th>
                            <th>Lure</th>
                            <th>Date</th>
                            <th>ID</th>
                        </tr>

                        ${createCatchRows(catches)}
                    </table>

                    <p>
                        <a href="/">Return to Fishing Tracker</a>
                    </p>

                    <p>
                        <a href="/stats">View Fishing Statistics</a>
                    </p>
                </section>
            </main>
        </body>
        </html>
    `;
}


// Adds a new catch to the server.
function addCatchHandler(request, response) {
    const fish = request.body;

    if (!isValidCatch(fish)) {
        response.status(400).json({
            error: "Please provide valid catch information."
        });

        return;
    }

    const newCatch = {
        id: Date.now().toString(),
        species: String(fish.species).trim(),
        location: String(fish.location).trim(),
        length: Number(fish.length),
        lure: String(fish.lure).trim(),
        date: String(fish.date).trim()
    };

    catches.push(newCatch);
    saveCatches();

    response.status(201).json(newCatch);
}


// Returns catches and applies optional filters.
app.get("/api/catches", function (request, response) {
    const speciesSearch = String(
        request.query.species || ""
    ).toLowerCase();

    const locationSearch = String(
        request.query.location || ""
    ).toLowerCase();

    const minimumLength = Number(request.query.minLength);

    const filteredCatches = catches.filter(function (fish) {
        const matchesSpecies =
            fish.species.toLowerCase().includes(speciesSearch);

        const matchesLocation =
            fish.location.toLowerCase().includes(locationSearch);

        const matchesMinimumLength =
            !request.query.minLength ||
            fish.length >= minimumLength;

        return (
            matchesSpecies &&
            matchesLocation &&
            matchesMinimumLength
        );
    });

    response.json(filteredCatches);
});


// Adds a catch through the main API route.
app.post("/api/catches", addCatchHandler);


// Adds a catch through the older route.
app.post("/catches", function (request, response) {
    addCatchHandler(request, {
        status: function () {
            return {
                json: function () {
                    response.redirect("/stats");
                }
            };
        }
    });
});


// Edits an existing catch.
app.put("/api/catches/:id", function (request, response) {
    const catchIndex = catches.findIndex(function (fish) {
        return fish.id === request.params.id;
    });

    if (catchIndex === -1) {
        response.status(404).json({
            error: "Catch not found."
        });

        return;
    }

    const updatedCatch = {
        id: catches[catchIndex].id,
        species: request.body.species,
        location: request.body.location,
        length: request.body.length,
        lure: request.body.lure,
        date: request.body.date
    };

    if (!isValidCatch(updatedCatch)) {
        response.status(400).json({
            error: "Please provide valid catch information."
        });

        return;
    }

    updatedCatch.length = Number(updatedCatch.length);
    catches[catchIndex] = updatedCatch;

    saveCatches();

    response.json(updatedCatch);
});


// Deletes an existing catch.
app.delete("/api/catches/:id", function (request, response) {
    const catchIndex = catches.findIndex(function (fish) {
        return fish.id === request.params.id;
    });

    if (catchIndex === -1) {
        response.status(404).json({
            error: "Catch not found."
        });

        return;
    }

    const deletedCatch = catches.splice(catchIndex, 1)[0];

    saveCatches();

    response.json(deletedCatch);
});


// Sends the main HTML page.
app.get("/", function (request, response) {
    response.sendFile(path.join(__dirname, "index.html"));
});


// Sends the CSS file.
app.get("/style.css", function (request, response) {
    response.sendFile(path.join(__dirname, "style.css"));
});


// Sends the browser JavaScript file.
app.get("/script.js", function (request, response) {
    response.sendFile(path.join(__dirname, "script.js"));
});


// Sends the statistics page.
app.get("/stats", function (request, response) {
    response.send(createStatsPage());
});


// Sends the detailed catch log page.
app.get("/catches", function (request, response) {
    response.send(createCatchesPage());
});


// Handles unknown pages.
app.use(function (request, response) {
    response.status(404).send("<h1>404</h1><p>Page not found.</p>");
});


// Starts the Express server.
app.listen(port, function () {
    console.log(`Express server running at http://localhost:${port}`);
});